let cachedFullCatalog: string[] | null = null;

/** Deduplicated catalog for preload — nav chrome, enums, and common page copy. */
export function getFullUiCatalog(): string[] {
  if (cachedFullCatalog) return cachedFullCatalog;
  cachedFullCatalog = [
    ...new Set([
      ...WEB_UI_CATALOG,
      ...collectEnumLabelStrings(),
      ...EXTRA_PAGE_CATALOG,
      ...ANALYTICS_CATALOG,
    ]),
  ];
  return cachedFullCatalog;
}
