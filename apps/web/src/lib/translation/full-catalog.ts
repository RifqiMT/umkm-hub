/** Enum and period labels used across feature pages. */
function collectEnumLabelStrings(): string[] {
  const strings = new Set<string>();
  for (const group of Object.values(LABELS)) {
    for (const label of Object.values(group)) {
      strings.add(label);
    }
  }
  for (const label of Object.values(DASHBOARD_PERIOD_LABELS)) {
    strings.add(label);
  }
  return [...strings];
}

